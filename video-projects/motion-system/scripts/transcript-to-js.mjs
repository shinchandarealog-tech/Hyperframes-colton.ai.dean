#!/usr/bin/env node
// Convert a word-level transcript.json (from `hyperframes transcribe`) into a
// .js data file the compositions can load synchronously (no runtime fetch).
// Usage: node scripts/transcript-to-js.mjs <transcript.json> <out.js>
import { readFileSync, writeFileSync } from "node:fs";

const [src, out] = process.argv.slice(2);
if (!src || !out) {
  console.error("usage: transcript-to-js.mjs <transcript.json> <out.js>");
  process.exit(1);
}
const words = JSON.parse(readFileSync(src, "utf8")).map((w) => ({
  text: w.text,
  start: +w.start.toFixed(3),
  end: +w.end.toFixed(3),
}));
writeFileSync(
  out,
  `// Generated by scripts/transcript-to-js.mjs from ${src} — do not edit by hand.\n` +
    `window.MS_TRANSCRIPTS = window.MS_TRANSCRIPTS || {};\n` +
    `window.MS_TRANSCRIPTS[${JSON.stringify(out.split("/").slice(-2, -1)[0])}] = ${JSON.stringify(words)};\n`,
);
console.log(`${words.length} words -> ${out}`);
