// Generates index.html (the render composition) from edit-data/beats.json
// using the same design engine the builder previews with (builder/designs.js).
// Run from the project folder:  node scripts/build_index.cjs
const fs = require("fs");
const path = require("path");

function build(projectDir) {
  const dir = projectDir || path.join(__dirname, "..");
  delete require.cache[require.resolve(path.join(dir, "builder/designs.js"))];
  const D = require(path.join(dir, "builder/designs.js"));
  const P = JSON.parse(fs.readFileSync(path.join(dir, "edit-data/beats.json"), "utf8"));
  const total = P.meta.duration;

  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=1080, height=1920">
<title>Udaan Cricket Academy — Admissions Reel</title>
<!-- GENERATED by scripts/build_index.cjs from edit-data/beats.json — edit in the builder, not here -->
<script src="assets/gsap.min.js"></script>
<script src="builder/designs.js"></script>
<style>
html,body{margin:0;padding:0;background:#14213D;}
${D.css("")}
</style>
</head>
<body>
  <div id="root" data-composition-id="udaan-reel" data-start="0" data-duration="${total.toFixed(3)}" data-width="1080" data-height="1920">
${D.markup(P, "")}
    <audio id="vo" src="${P.meta.vo}" data-start="0" data-duration="${P.meta.voDuration.toFixed(3)}" data-track-index="30" data-volume="1"></audio>
  </div>
<script>
  window.__timelines = window.__timelines || {};
  const PROJECT = ${JSON.stringify(P)};
  const tl = gsap.timeline({ paused: true });
  UdaanDesigns.buildTimeline(tl, PROJECT);
  window.__timelines["udaan-reel"] = tl;
</script>
</body>
</html>
`;
  fs.writeFileSync(path.join(dir, "index.html"), html);
  return { beats: P.beats.length, duration: total };
}

module.exports = { build };
if (require.main === module) console.log("index.html written", build());
