// Builds overlay.js, measures layout with real fonts in Chromium, then writes layout.js + index.html.
// Usage (from the project folder): node edit-data/build.mjs
import fs from "node:fs";
import path from "node:path";
import http from "node:http";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const P = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const E = path.join(P, "edit-data");
const GSAP_LOCAL = process.env.GSAP_LOCAL; // optional local gsap.min.js when the CDN is unreachable

// 1. overlay.js with the face track baked in
const faces = fs.readFileSync(path.join(E, "faces10.json"), "utf8").trim();
fs.writeFileSync(path.join(P, "overlay.js"), fs.readFileSync(path.join(E, "overlay.src.js"), "utf8").replace("/*FACES*/[]", faces));

// 2. measurement page: same composition, built after the real fonts load
const tpl = fs.readFileSync(path.join(E, "index.template.html"), "utf8");
const fontsLink = "<style>\n" + fs.readFileSync(path.join(E, "fonts.css"), "utf8") + "  </style>";
const measureHtml = tpl.replace("<!--FONTS-->", fontsLink).replace("<!--LAYOUT-->", "").replace("<!--SFX-->", "")
  .replace(/<script>\s*window.__timelines[\s\S]*?<\/script>/, `<script>
    Promise.all(['300 58px "Exo 2"','900 96px "Orbitron"','600 46px "Inter"','700 54px "Inter"','500 32px "Inter"'].map((f) => document.fonts.load(f))).then(() => setTimeout(() => { window.buildUniverseOverlay(document.getElementById("back"), document.getElementById("front"), 56.2); window.__done = true; }, 300));
  </script>`);
fs.writeFileSync(path.join(P, "measure.html"), measureHtml);

const server = http.createServer((req, res) => {
  const f = path.join(P, decodeURIComponent(req.url.split("?")[0]));
  if (!f.startsWith(P) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { "content-type": f.endsWith(".html") ? "text/html" : f.endsWith(".js") ? "application/javascript" : "application/octet-stream" });
  fs.createReadStream(f).pipe(res);
}).listen(0);
const port = server.address().port;
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1080, height: 1920 } });
if (GSAP_LOCAL) await page.route("**/gsap.min.js", (r) => r.fulfill({ path: GSAP_LOCAL, contentType: "application/javascript" }));
await page.route("**/*.{mp4,webm}", (r) => r.abort());
await page.goto(`http://localhost:${port}/measure.html`);
await page.waitForFunction(() => window.__done === true, null, { timeout: 30000 });
const fontsOk = await page.evaluate(() => ["Exo 2", "Orbitron", "Inter"].map((f) => [f, [...document.fonts].some((x) => x.family.replace(/[\x27"]/g, "") === f && x.status === "loaded")]));
const rec = await page.evaluate(() => window.__REC);
const events = await page.evaluate(() => window.__SFX_EVENTS);
await browser.close(); server.close();
fs.unlinkSync(path.join(P, "measure.html"));
console.log("fonts loaded:", JSON.stringify(fontsOk), "layout values:", rec.length, "sfx events:", events.length);

// 3. layout.js
fs.writeFileSync(path.join(P, "layout.js"), "/* generated by edit-data/build.mjs — measured with real fonts */\nwindow.__LAYOUT = " + JSON.stringify(rec) + ";\n");

// 4. SFX clips (Clean pack). Start = event - peak so the loudest moment lands on the beat.
const KIND = { emph: ["sfx/swoosh-short.mp3", 0.095, 0.29, 0.3], ui: ["sfx/pop-low.mp3", 0.032, 0.14, 0.35], note: ["sfx/iphone-receive.wav", 0.341, 0.79, 0.3] };
const trackEnd = [0, 0, 0, 0]; let n = 0;
const tags = events.sort((a, b) => a.t - b.t).map((ev) => {
  const [src, peak, dur, vol] = KIND[ev.kind]; const start = Math.max(0, +(ev.t - peak).toFixed(3));
  let tr = trackEnd.findIndex((end) => end <= start); if (tr < 0) tr = 0; trackEnd[tr] = start + dur + 0.01;
  return `    <audio id="sfx-${++n}" src="assets/${src}" data-start="${start}" data-duration="${dur}" data-track-index="${3 + tr}" data-volume="${vol}"></audio>`;
});
const html = tpl.replace("<!--FONTS-->", fontsLink).replace("<!--LAYOUT-->", '<script src="layout.js"></script>').replace("<!--SFX-->", tags.join("\n"));
fs.writeFileSync(path.join(P, "index.html"), html);
console.log("wrote index.html with", tags.length, "sfx clips");
